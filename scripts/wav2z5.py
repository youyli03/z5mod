#!/usr/bin/env python3
"""Convert an arbitrary WAV into the format the camera's audio engine plays.

The engine wants raw linear PCM: 48 kHz, 2 channels, signed 16-bit little
endian. A WAV file is exactly that plus a header, so this script resamples,
remixes and requantises whatever you give it.

Usage:
    python scripts/wav2z5.py in.wav -o build/SND.WAV
    python scripts/wav2z5.py in.wav -o build/SND.WAV --seconds 0.9 --trim --normalize
    python scripts/wav2z5.py in.wav --header build/snd_pcm.h

Requires numpy (resampling and remixing are written with it):
    python -m pip install numpy

This script is a standalone utility. It is not part of any build contract: the
module build can consume either the produced WAV or the generated C header.
"""
from __future__ import annotations

import argparse
import sys
import wave

try:
    import numpy as np
except ImportError:                                    # pragma: no cover
    sys.exit("this script needs numpy:  python -m pip install numpy")

RATE = 48000
CHANNELS = 2


def read_wav(path: str):
    with wave.open(path, "rb") as w:
        frames = w.getnframes()
        channels = w.getnchannels()
        width = w.getsampwidth()
        rate = w.getframerate()
        raw = w.readframes(frames)
    if width == 1:
        samples = (np.frombuffer(raw, dtype=np.uint8).astype(np.int32) - 128) << 8
    elif width == 2:
        samples = np.frombuffer(raw, dtype="<i2").astype(np.int32)
    elif width == 3:
        b = np.frombuffer(raw, dtype=np.uint8).reshape(-1, 3).astype(np.int32)
        v = (b[:, 0] << 8) | (b[:, 1] << 16) | (b[:, 2] << 24)
        samples = v >> 16
    elif width == 4:
        samples = (np.frombuffer(raw, dtype="<i4") >> 16).astype(np.int32)
    else:
        raise SystemExit("unsupported sample width: %d bytes" % width)
    return samples.reshape(-1, channels), rate, channels


def to_stereo(samples, channels: int):
    if channels == 1:
        return np.repeat(samples, 2, axis=1)
    if channels == 2:
        return samples
    return samples[:, :2]


def resample(samples, src_rate: int, dst_rate: int):
    if src_rate == dst_rate:
        return samples
    n_out = int(round(samples.shape[0] * dst_rate / src_rate))
    if n_out <= 0:
        return samples[:0]
    x = np.arange(n_out) * (src_rate / dst_rate)
    i0 = np.floor(x).astype(np.int64)
    i1 = np.minimum(i0 + 1, samples.shape[0] - 1)
    frac = (x - i0).reshape(-1, 1)
    return (samples[i0] * (1.0 - frac) + samples[i1] * frac).astype(np.int32)


def trim_silence(samples, threshold: int = 64):
    magnitude = np.abs(samples).max(axis=1)
    nonzero = np.nonzero(magnitude > threshold)[0]
    if len(nonzero) == 0:
        return samples
    return samples[nonzero[0]: nonzero[-1] + 1]


def write_wav(path: str, samples) -> None:
    data = np.clip(samples, -32768, 32767).astype("<i2").tobytes()
    with wave.open(path, "wb") as w:
        w.setnchannels(samples.shape[1])
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(data)


def write_header(path: str, samples) -> None:
    data = np.clip(samples, -32768, 32767).astype("<i2").tobytes()
    with open(path, "w", encoding="ascii") as f:
        f.write("/* generated by scripts/wav2z5.py - 48 kHz stereo 16-bit PCM */\n")
        f.write("#define SND_PCM_FRAMES %du\n" % (len(data) // 4))
        f.write("#define SND_PCM_BYTES  %du\n" % len(data))
        f.write("static const unsigned char snd_pcm[%d] = {\n" % len(data))
        for i in range(0, len(data), 16):
            f.write("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
        f.write("};\n")


def main() -> int:
    ap = argparse.ArgumentParser(description="convert a WAV to the camera playback format")
    ap.add_argument("input")
    ap.add_argument("-o", "--output", help="write a ready-to-use WAV here")
    ap.add_argument("--header", help="write a C header with the PCM array here")
    ap.add_argument("--seconds", type=float, default=1.0, help="maximum length (default 1.0)")
    ap.add_argument("--mono", action="store_true", help="write mono instead of stereo")
    ap.add_argument("--dup6", action="store_true",
                    help="8 kHz stream with each sample held for six frames (48 kHz)")
    ap.add_argument("--gain", type=float, default=1.0)
    ap.add_argument("--trim", action="store_true", help="trim leading and trailing silence")
    ap.add_argument("--normalize", action="store_true", help="scale the peak to 90%% full scale")
    args = ap.parse_args()

    samples, src_rate, channels = read_wav(args.input)
    samples = to_stereo(samples, channels)
    if args.dup6:
        samples = np.repeat(resample(samples, src_rate, 8000), 6, axis=0)
    else:
        samples = resample(samples, src_rate, RATE)
    if args.trim:
        samples = trim_silence(samples)

    limit = int(args.seconds * RATE)
    if samples.shape[0] > limit:
        samples = samples[:limit]

    if args.mono and samples.shape[1] == 2:
        samples = samples[:, :1]

    scaled = samples.astype(np.float64) * args.gain
    if args.normalize:
        peak = np.abs(scaled).max()
        if peak > 0:
            scaled *= (0.9 * 32767.0) / peak
    samples = np.clip(scaled, -32768, 32767).astype(np.int32)

    if args.header:
        write_header(args.header, samples)
        print("header -> %s (%d frames, %.3f s)" % (args.header, samples.shape[0], samples.shape[0] / RATE))
    if args.output:
        write_wav(args.output, samples)
        print("wav    -> %s (%d frames, %.3f s, %d bytes)" %
              (args.output, samples.shape[0], samples.shape[0] / RATE, samples.shape[0] * 4))
    if not args.header and not args.output:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
