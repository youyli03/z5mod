def apply(module: bytes) -> bytes:
    """Return the module with the loader installed, CRC resealed."""
    if binascii.crc_hqx(module, 0):
        raise ValueError('input module CRC residue is not zero')
    body = module[:-2]
    current = struct.unpack_from('<I', body, LITERAL_OFFSET)[0]
    if current != ORIGINAL_CALLBACK:
        raise ValueError('draw callback literal is 0x%08x, expected 0x%08x; '
                         'this module is not the one this patch was built for'
                         % (current, ORIGINAL_CALLBACK))

    append_at = (len(body) + 7) & ~7
    code_at = BASE + append_at + len(PATH)
    out = bytearray(body)
    out += bytes(append_at - len(out)) + PATH + CODE
    struct.pack_into('<I', out, LITERAL_OFFSET, code_at | 1)
    out += binascii.crc_hqx(out, 0).to_bytes(2, 'big')
    if binascii.crc_hqx(out, 0):
        raise ValueError('internal error: resealed module CRC is not zero')
    return bytes(out)
