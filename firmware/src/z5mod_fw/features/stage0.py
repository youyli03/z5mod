"""SD module host: load and run a .Z5M from the card on every menu redraw.

The patch redirects one draw callback, appends the loader code after the module
image, and points the callback literal at that code. It validates the literal it
replaces, so it refuses to run on any module but the one it was built for.

The appended code is pre-assembled machine code, kept as bytes so building never
needs an assembler. It is position-fixed: everything inside it targets this exact
module, which is why the input hash is checked before the patch runs.

What the loader does, in order:
  1. runs on the module row's draw callback only;
  2. closes the file before allocating, so the file service and the memory
     service are never busy at the same time;
  3. reads A:\\Z5APP.BIN in 848-byte chunks, checks the magic and the CRC;
  4. flushes the instruction cache, calls the image, frees it;
  5. falls through to the original callback, which draws the row.
"""
import binascii
import struct

# Module offsets and addresses this patch depends on.
LITERAL_OFFSET = 0x492224          # the draw callback literal inside the module
ORIGINAL_CALLBACK = 0x104b1f59     # the value that literal must currently hold
BASE = 0x10020000                  # module load address

# Path the loader reads, padded to eight bytes.
PATH = b'A:\\Z5APP.BIN\x00\x00\x00\x00'

# Appended loader code (pre-assembled; see the module docstring).
